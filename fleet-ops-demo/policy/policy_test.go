package policy

import (
	"strings"
	"testing"
)

func TestRequiredByRoot(t *testing.T) {
	const generated = "default allow := false\n\nallow {\n\tpolicies.allow\n}\n\nallow {\n\tcustom.allow\n}\n"
	const wired = "default allow := false\n\nallow {\n\tpolicies.allow\n\tcustom.acting_org_ok\n\tcustom.fleet_rules_ok\n}\n\nallow {\n\tcustom.extra_allow\n\tcustom.acting_org_ok\n\tcustom.fleet_rules_ok\n}\n"
	// The custom requirements are there, but only as comments next to Permit's own rules.
	const commentedOut = generated + "\n# allow {\n# \tpolicies.allow\n# \tcustom.acting_org_ok\n# \tcustom.fleet_rules_ok\n# }\n"
	const oneUnwired = "allow {\n\tpolicies.allow\n\tcustom.acting_org_ok\n\tcustom.fleet_rules_ok\n}\n\nallow {\n\tcustom.allow\n}\n"
	// The same requirements in the other order mean the same.
	const swapped = "allow {\n\tpolicies.allow\n\tcustom.fleet_rules_ok\n\tcustom.acting_org_ok\n}\n"
	const negated = "allow {\n\tpolicies.allow\n\tnot custom.acting_org_ok\n\tcustom.fleet_rules_ok\n}\n"
	const crlf = "allow {\r\n\tpolicies.allow\r\n\tcustom.acting_org_ok\r\n\tcustom.fleet_rules_ok\r\n}\r\n"

	for name, tc := range map[string]struct {
		root string
		want bool
	}{
		"generated by Permit":                   {generated, false},
		"every allow requires them":             {wired, true},
		"as RootAllow installs them":            {"package permit.root\n\ndefault allow := false\n\n" + RootAllow + "\n", true},
		"requirements commented out":            {commentedOut, false},
		"one allow not wired":                   {oneUnwired, false},
		"no allow rules":                        {"default allow := false\n", false},
		"requirements in the other order":       {swapped, true},
		"a requirement negated":                 {negated, false},
		"Windows line endings":                  {crlf, true},
		"an allow rule of another shape":        {wired + "allow = true { input.x }\n", false},
		"allowing_sources is not an allow rule": {wired + "allowing_sources := policies.__allow_sources\n", true},
	} {
		t.Run(name, func(t *testing.T) {
			if got := RequiredByRoot(tc.root); got != tc.want {
				t.Errorf("got %v, want %v", got, tc.want)
			}
		})
	}
}

// Reordering the requirements in RootAllow must not make `make verify` call the installed rules
// missing: the writer (RootAllow) and the reader (RequiredByRoot) live here, together.
func TestRootAllowReorderedStillRecognized(t *testing.T) {
	reordered := strings.NewReplacer(
		"\tcustom.acting_org_ok\n\tcustom.fleet_rules_ok", "\tcustom.fleet_rules_ok\n\tcustom.acting_org_ok",
	).Replace(RootAllow)
	if reordered == RootAllow {
		t.Fatal("the replacement didn't apply: update this test with RootAllow")
	}
	if !RequiredByRoot("default allow := false\n\n" + reordered + "\n") {
		t.Error("RootAllow with its requirements reordered isn't recognized")
	}
}

func TestVersion(t *testing.T) {
	for name, tc := range map[string]struct{ module, want string }{
		"stamped":       {Custom("2026-10-13T10:00:00Z"), "2026-10-13T10:00:00Z"},
		"not installed": {"", ""},
		"CRLF":          {"package permit.custom\r\npolicy_version := \"v2\"\r\n", "v2"},
	} {
		t.Run(name, func(t *testing.T) {
			if got := Version(tc.module); got != tc.want {
				t.Errorf("got %q, want %q", got, tc.want)
			}
		})
	}
}
